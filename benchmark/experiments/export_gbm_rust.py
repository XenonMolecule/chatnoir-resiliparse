#!/usr/bin/env python
"""Export a sklearn GradientBoostingRegressor to Rust code (nested if-else)."""
import sys, joblib
m = joblib.load(sys.argv[1])
base = ["tag","depth","log_text_len","link_density","n_links","page_ld","frac_page",
        "punct","digit","upper","avgw","nav","footer","header","sidebar","social",
        "article","chrome","byline","widget","recommended","comments",
        "headings","page_headings","prev_ld","next_ld","prev_len","next_len"]
v4 = ["page_forms","page_articles","page_comment_cls"]
v5 = v4 + ["page_nav_share","page_generator","page_n_blocks"]
nf = m.n_features_in_
if nf == 66:
    names = base + v5 + [f"wb[{i}]" for i in range(32)]
elif nf == 63:
    names = base + v4 + [f"wb[{i}]" for i in range(32)]
elif nf == 60:
    names = base + [f"wb[{i}]" for i in range(32)]
else:
    raise SystemExit(f"unexpected n_features {nf}")
out = []
out.append("// AUTO-GENERATED by export_gbm_rust.py — do not edit by hand.")
out.append("// Model: GradientBoostingRegressor n=%d depth=%d lr=%s" % (
    m.n_estimators, m.max_depth, m.learning_rate))
out.append("#[derive(Clone, Copy, Default)]")
out.append("pub struct BlockFeatures {")
for n in names:
    if not n.startswith("wb["):
        out.append(f"    pub {n}: f64,")
out.append("    pub wb: [f64; 32],")
out.append("}")
def emit_tree(t, idx):
    lines = [f"fn gbm_tree_{idx}(f: &BlockFeatures) -> f64 {{"]
    def rec(node, ind):
        pad = "    " * ind
        if t.children_left[node] == -1:
            lines.append(f"{pad}{t.value[node][0][0]:.6}")
            return
        fn, thr = names[t.feature[node]], t.threshold[node]
        lines.append(f"{pad}if f.{fn} <= {thr:.6} {{")
        rec(t.children_left[node], ind+1)
        lines.append(f"{pad}}} else {{")
        rec(t.children_right[node], ind+1)
        lines.append(f"{pad}}}")
    rec(0, 1)
    lines.append("}")
    return lines
for i, est in enumerate(m.estimators_[:, 0]):
    out.extend(emit_tree(est.tree_, i))
init = float(m.init_.constant_[0][0])
out.append("pub fn score_block(f: &BlockFeatures) -> f64 {")
out.append(f"    let mut s = {init:.6}f64;")
out.append(f"    let lr = {m.learning_rate};")
calls = " + ".join(f"gbm_tree_{i}(f)" for i in range(m.n_estimators))
# chunk the sum to avoid giant expressions
out.append("    let mut acc = 0.0f64;")
for i in range(m.n_estimators):
    out.append(f"    acc += gbm_tree_{i}(f);")
out.append("    s += lr * acc;")
out.append("    s")
out.append("}")
path = sys.argv[2] if len(sys.argv) > 2 else "resiliparse-rs/src/extract/block_model.rs"
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {path}: {len(out)} lines")
